int? getBookNumberByName(String? bookName, String lang) {
  if (bookName == null || bookName.trim().isEmpty) return null;
  final String prefix = lang.length >= 2
      ? lang.substring(0, 2).toLowerCase()
      : "pt";
  for (final p in [prefix, "pt", "en", "es"]) {
    final int? nr = bookMapping[p]?[bookName];
    if (nr != null) return nr;
  }
  return null;
}

int getChapterCountForBook(String? bookName, String lang) {
  final int? bookNr = getBookNumberByName(bookName, lang);
  if (bookNr == null) return 150;
  return bookChapterVerseCounts[bookNr]?.length ?? 50;
}

int getVerseCountForChapter(String? bookName, int chapter, String lang) {
  final int? bookNr = getBookNumberByName(bookName, lang);
  final List<int>? chapters = bookNr != null
      ? bookChapterVerseCounts[bookNr]
      : null;
  if (chapters == null || chapters.isEmpty) return 176;
  final int idx = (chapter - 1).clamp(0, chapters.length - 1);
  return chapters[idx];
}



